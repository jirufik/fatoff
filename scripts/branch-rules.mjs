/**
 * Правила веток: что во что можно сливать и что после этого пересобирается.
 *
 * Вынесено отдельным файлом, потому что это единственное место, где правило
 * записано; хуки его только зовут. Заодно правило становится проверяемым:
 * у него есть тесты, а не «кажется, работает».
 */

/** Ветка прода. Всё, что в ней, — запущено и работает. */
export const MAIN = 'main';

/** Ветка общей проверки. Через неё проходит всё, что попадает в прод. */
export const DEVELOP = 'develop';

/**
 * Переменная, которой подтверждается согласие человека на слияние.
 *
 * Хук не умеет отличить одобренную работу от неодобренной — это знает только
 * человек. Поэтому слияние в общие ветки требует явно передать согласие: забыть
 * спросить теперь нельзя молча, отказ виден в терминале (D-069).
 */
export const APPROVAL_VAR = 'APPROVED_BY';

/**
 * Можно ли слить `from` в `into`.
 *
 * Возвращает `null`, когда можно, и объяснение, когда нельзя. Объяснение —
 * человеку у терминала, поэтому оно длиннее кода правила.
 *
 * `approvedBy` — значение переменной согласия; пустое означает «не спрашивали».
 */
export function mergeRefusal(into, from, approvedBy = '') {
  if (into === MAIN && from !== DEVELOP) {
    return (
      `В ${MAIN} сливается только ${DEVELOP}, а не «${from}».\n` +
      `${MAIN} — это то, что запущено и чем пользуются; всё попадает туда одним путём,\n` +
      `через общую проверку на ${DEVELOP}. Сделайте так:\n\n` +
      `  git switch ${DEVELOP} && git merge --no-ff ${from}\n` +
      `  # проверка на окружении develop\n` +
      `  git switch ${MAIN} && git merge --no-ff ${DEVELOP}\n`
    );
  }

  if (into === DEVELOP && (from === MAIN || from === DEVELOP)) {
    return (
      `В ${DEVELOP} сливаются ветки задач, а не «${from}».\n` +
      `Работа идёт в своей ветке, показывается из неё и только потом попадает сюда.\n`
    );
  }

  if ((into === MAIN || into === DEVELOP) && approvedBy.trim() === '') {
    return (
      `Слияние «${from}» в ${into} не подтверждено.\n\n` +
      `Работа сначала показывается из своей ветки, и только после согласия человека\n` +
      `попадает в общую (D-069). Хук не может отличить одобренное от неодобренного,\n` +
      `поэтому согласие передаётся явно:\n\n` +
      `  ${APPROVAL_VAR}="кто одобрил" git merge --no-ff ${from}\n\n` +
      `Подставлять сюда что попало, не спросив, — то же самое, что слить без спроса.\n`
    );
  }

  return null;
}

/**
 * Можно ли коммитить прямо в эту ветку.
 *
 * Ни в `main`, ни в `develop` — нельзя: обе собираются только слиянием, и
 * обычный коммит туда обходит правило молча. Раньше запрет стоял только на
 * `main`, и в открытую половину я же и провалился: коммит ушёл прямо в
 * `develop`, минуя ветку задачи (D-069).
 */
export function commitRefusal(branch) {
  if (branch === MAIN || branch === DEVELOP) {
    const built = branch === MAIN ? `слиянием ${DEVELOP}` : 'слиянием веток задач';
    return (
      `Прямой коммит в ${branch} запрещён.\n` +
      `${branch} собирается только ${built}. Начните с ветки задачи:\n\n` +
      `  git switch -c feature/<что-делаем>\n\n` +
      `Уже наделали в ${branch}? Перенесите коммиты в ветку и верните ${branch} назад:\n\n` +
      `  git branch feature/<что-делаем>\n` +
      `  git reset --hard <последний общий коммит>\n`
    );
  }
  return null;
}

/**
 * Какой контур пересобирать после слияния в эту ветку.
 *
 * Фича-ветки в докер не уезжают вовсе — для них `null`.
 */
export function environmentOf(branch) {
  if (branch === MAIN) {
    return { name: 'прод', port: 4090, commands: [['pnpm', 'db:up'], ['pnpm', 'docker:up']] };
  }
  if (branch === DEVELOP) {
    return { name: 'develop', port: 4092, commands: [['pnpm', 'develop:up']] };
  }
  return null;
}
