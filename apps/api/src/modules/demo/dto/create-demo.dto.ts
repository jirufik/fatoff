import { IsIn, IsOptional } from 'class-validator';

export class CreateDemoDto {
  /**
   * Язык, на котором писать названия еды.
   *
   * Названия продуктов не переводятся ни у демо, ни у настоящего аккаунта: их
   * пишет человек в своём приложении (D-068). Поэтому язык фиксируется в момент
   * создания, а не берётся из подписи интерфейса при каждом показе.
   */
  @IsOptional()
  @IsIn(['ru', 'en'])
  locale?: 'ru' | 'en';
}
