/**
 * Отказ загрузки из Drive — кодом, а не готовой фразой.
 *
 * Первая версия складывала в журнал русский текст ошибки и показывала его как
 * есть. На английском экране он оставался русским — и это поймала проверка, а
 * не человек. Сервер не сочиняет фраз (D-044): он говорит, что случилось, а
 * предложение собирает интерфейс.
 */
export class DriveFailure extends Error {
  constructor(
    readonly code: string,
    /** Подстановки; у неизвестной ошибки — исходный текст. */
    readonly params?: Record<string, string | number>,
  ) {
    super(code);
  }
}
