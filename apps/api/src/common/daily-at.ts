/**
 * «Ежедневно в ЧЧ:ММ» — общая часть расписаний.
 *
 * Задача просыпается каждую минуту и смотрит, чьё время настало. Так проще
 * там, где это важно: время меняют прямо в интерфейсе, и при отдельной задаче
 * на аккаунт их пришлось бы снимать и перерегистрировать на каждое сохранение
 * настроек — с попаданием в момент, когда задача уже выполняется.
 *
 * Вынесено из модуля Drive, когда такое же расписание понадобилось
 * синхронизации YAZIO: две копии этой логики разошлись бы на первой же правке.
 */

/** Время сейчас в виде `ЧЧ:ММ` — по часам машины, как их видит человек. */
export function hhmmOf(at: Date): string {
  return `${String(at.getHours()).padStart(2, '0')}:${String(at.getMinutes()).padStart(2, '0')}`;
}

/** Годится ли строка как время расписания. */
export function isDailyAt(value: string): boolean {
  return /^([01]\d|2[0-3]):[0-5]\d$/.test(value);
}

/**
 * Память о том, что уже сделано в эту минуту.
 *
 * Нужна не от лишней осторожности: часы машины могут дёрнуться назад — при
 * поправке по NTP или переводе времени, — и тогда одна и та же минута наступит
 * дважды. Синхронизация от этого не сломается, но запустится впустую.
 */
export class OncePerMinute {
  private readonly seen = new Set<string>();

  /** `true`, если для этого ключа в эту минуту ещё не делали. */
  claim(key: string, at: Date): boolean {
    const stamp = `${at.toISOString().slice(0, 10)} ${hhmmOf(at)}`;
    const full = `${key}:${stamp}`;
    if (this.seen.has(full)) return false;

    this.seen.add(full);
    // множество не должно расти вечно: вчерашние отметки больше не нужны
    if (this.seen.size > 64) {
      for (const item of this.seen) if (!item.endsWith(stamp)) this.seen.delete(item);
    }
    return true;
  }
}
